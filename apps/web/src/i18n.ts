export async function createTranslations(language: LocaleChoice | string = "en"): Promise<i18n> {
  const instance = createInstance();
  await instance
    .use(ICU)
    .use(initReactI18next)
    .init({
      lng: language,
      fallbackLng: "en",
      supportedLngs: ["en", "es"],
      resources: { en: { translation: en }, es: { translation: es } },
      interpolation: { escapeValue: false },
      initAsync: false,
      returnNull: false,
    });
  return instance;
}
