import { expect, test } from "@playwright/test";
import { scanIndexedStory, storySlug } from "./axe-story-gate";
import { assertStoryScanCoverage, storiesForFamily } from "./story-inventory";

const story = (state: string) => `/iframe.html?id=primitives-chatbubble--${state}&viewMode=story`;

test("B5c tutor and learner display named semantic articles with different approved surface recipes", async ({
  page,
}) => {
  await page.goto(story("default"));
  const tutor = page.getByRole("article", { name: "Sample study guide" });
  await expect(tutor).toHaveClass(/glass-reading/);
  await expect(tutor).toHaveAttribute("data-speaker", "tutor");
  await expect(tutor.getByRole("heading", { name: "Sample study guide" })).toBeVisible();
  await expect(tutor).toContainText("not generated by a model");
  const readingStyle = await tutor.evaluate((node) => {
    const styles = getComputedStyle(node);
    return { filter: styles.backdropFilter, background: styles.backgroundColor };
  });
  expect(readingStyle.background).not.toBe("rgba(0, 0, 0, 0)");
  await page.goto(story("learner"));
  const learner = page.getByRole("article", { name: "Sample learner" });
  await expect(learner).toHaveClass(/glass-raised/);
  await expect(learner).toHaveAttribute("data-speaker", "learner");
  await expect(learner.getByText("Could we revisit the explanation?")).toBeVisible();
  await expect(learner.locator("button,a,input,[tabindex]")).toHaveCount(0);
});

test("B5c progress is presentational and empty content is not invented or announced as live output", async ({
  page,
}) => {
  await page.goto(story("streaming"));
  const bubble = page.locator(".lyceum-chat-bubble");
  await expect(bubble).toHaveAttribute("data-streaming", "true");
  await expect(bubble).toContainText("Partial example explanation");
  await expect(bubble).toContainText("Response in progress");
  await expect(bubble.locator("[aria-live],[role='status'],[role='log']")).toHaveCount(0);
  await page.goto(story("empty"));
  await expect(page.getByText("No message content")).toBeVisible();
  await expect(page.locator(".lyceum-chat-bubble__content")).not.toContainText("Hello");
});

test("B5c real RTL, 200% root text, short viewport and solid fallback remain usable", async ({
  page,
}) => {
  for (const state of ["rtl", "double-text", "long-text", "high-contrast", "opaque"]) {
    for (const viewport of [
      { width: 320, height: 640 },
      { width: 320, height: 256 },
    ]) {
      await page.setViewportSize(viewport);
      await page.goto(story(state));
      const bubble = page.getByRole("article");
      await expect(bubble).toBeVisible();
      const layout = await bubble.evaluate((node) => {
        const rect = node.getBoundingClientRect();
        const styles = getComputedStyle(node);
        return {
          left: rect.left,
          right: rect.right,
          width: document.documentElement.scrollWidth,
          viewport: innerWidth,
          background: styles.backgroundColor,
          filter: styles.backdropFilter,
        };
      });
      expect(layout.left, state).toBeGreaterThanOrEqual(-1);
      expect(layout.right, state).toBeLessThanOrEqual(viewport.width + 1);
      expect(layout.width, state).toBeLessThanOrEqual(layout.viewport + 1);
      if (state === "high-contrast" || state === "opaque") {
        expect(layout.filter, state).toBe("none");
      }
      if (state === "rtl") {
        await expect(bubble).toHaveAttribute("dir", "rtl");
        await expect(bubble).toHaveAttribute("lang", "ar");
      }
    }
  }
});

test("B5c complete generated story matrix has no tagged axe violations, no synthetic interaction states", async ({
  page,
}) => {
  test.setTimeout(240_000);
  const stories = storiesForFamily("ChatBubble");
  const checked: string[] = [];
  for (const entry of stories) {
    await page.goto(`/iframe.html?id=${entry.id}&viewMode=story`);
    const bubble = page.locator(".lyceum-chat-bubble");
    await expect(bubble).toBeVisible();
    const state = storySlug(entry);
    if (state === "hover") await bubble.hover();
    await expect(bubble.locator("a,button,input,[tabindex]")).toHaveCount(0);
    checked.push(await scanIndexedStory(page, entry, state));
  }
  assertStoryScanCoverage(stories, checked);
});
